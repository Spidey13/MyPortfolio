import { Fragment, useCallback, useEffect, useLayoutEffect, useRef, useState, type CSSProperties, type ReactNode } from "react";
import { FIRETRACE_CASE_STUDY as cs, type FireTraceLane } from "../../data/firetraceCaseStudy";
import { PremiereFooter, type PremierePageProps } from "./PremiereShared";

/** Shape of public/data/firetrace-scrub.json. */
interface ScrubChange {
  interval_h: number;
  delta_acres: number;
  added_acres: number;
  removed_acres: number;
  iou: number;
  label: string;
  caveats: string[];
}
interface ScrubFrame {
  id: string;
  observed_at: string;
  published_at: string;
  area: number;
  change: ScrubChange | null;
  d: string;
  add: string;
  rem: string;
}
interface ScrubData {
  vb: [number, number];
  unit: number;
  frames: ScrubFrame[];
  feds: string;
  lobe: [number, number];
  minor: string;
  index: string;
}

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
/** The Dome Fire flights fall inside PDT (UTC−7); shift once and read UTC fields. */
const pdt = (iso: string) => new Date(Date.parse(iso) - 7 * 3600e3);
const day = (d: Date) => `${MONTHS[d.getUTCMonth()]} ${d.getUTCDate()}`;
const clock = (d: Date) => {
  const h = d.getUTCHours();
  return `${h % 12 || 12}:${String(d.getUTCMinutes()).padStart(2, "0")} ${h >= 12 ? "PM" : "AM"}`;
};
const lag = (from: string, to: string) => {
  const minutes = Math.round((Date.parse(to) - Date.parse(from)) / 60000);
  return `${Math.floor(minutes / 60)} h ${minutes % 60} min`;
};
const acres = (value: number, digits = 1) =>
  value.toLocaleString("en-US", { minimumFractionDigits: digits, maximumFractionDigits: digits });
const trimmed = (value: number) => value.toLocaleString("en-US", { maximumFractionDigits: 2 });
const signed = (value: number) => `${value > 0 ? "+" : value < 0 ? "−" : ""}${trimmed(Math.abs(value))}`;

/** Generated by docs/design/firetrace/tools/build_scrub.mjs from FireTrace's geometry and records. */
const SCRUB_URL = "/data/firetrace-scrub.json";
const SCRUB_VIEW = [346, -10, 720, 1210] as const;
const DISAGREEMENT_VIEW = "40 10 1020 1160";

function useScrubData() {
  const [data, setData] = useState<ScrubData | null>(null);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    let live = true;
    fetch(SCRUB_URL)
      .then((response) => (response.ok ? response.json() : Promise.reject(new Error(String(response.status)))))
      .then((json: ScrubData) => { if (live) setData(json); })
      .catch(() => { if (live) setFailed(true); });
    return () => { live = false; };
  }, []);
  return { data, failed };
}

function withCode(text: string, terms: readonly string[]): ReactNode {
  const pattern = new RegExp(`(${terms.join("|")})`, "g");
  return text.split(pattern).map((part, i) =>
    terms.includes(part) ? <code key={i}>{part}</code> : <Fragment key={i}>{part}</Fragment>,
  );
}

function Readout({ frames, index }: { frames: ScrubFrame[]; index: number }) {
  const frame = frames[index];
  const previous = frames[index - 1];
  const flown = pdt(frame.observed_at);
  const published = pdt(frame.published_at);
  const change = frame.change;
  const revision = change?.label.includes("revision") ?? false;
  const notes = change ? change.caveats.map((key) => cs.scrub.caveats[key]).filter(Boolean) : [];

  return (
    <div className="ft-readout" aria-live="polite" aria-atomic="true">
      <p className="ft-when">{day(flown)}, {clock(flown)} PDT</p>
      <p className="ft-src">Airborne infrared heat perimeter, NIFC incident IR. Flight {index + 1} of {frames.length} shown.</p>
      <dl className="ft-facts">
        <dt>Mapped</dt><dd><strong>{acres(frame.area)} ac</strong>, computed from the outline</dd>
        <dt>Flown</dt><dd>{clock(flown)}, give or take 30 min</dd>
        <dt>Published</dt><dd>{day(published)}, {clock(published)}, {lag(frame.observed_at, frame.published_at)} after the flight</dd>
      </dl>
      <div className="ft-delta">
        {change && previous ? (
          <>
            <p className="ft-big">{signed(change.delta_acres)} ac<small>since {day(pdt(previous.observed_at))}, {change.interval_h} h earlier</small></p>
            <p>{trimmed(change.added_acres)} ac added and {trimmed(change.removed_acres)} ac removed. The two outlines overlap at IoU {change.iou}.</p>
            <p className={`ft-verdict${revision ? " is-revision" : ""}`}>
              {revision
                ? "A smaller outline here is a mapping revision, not a shrinking fire."
                : "Net increase in mapped area. Added area can include redrawn edges as well as new burning."}
            </p>
            {notes.length ? <ul className="ft-notes">{notes.map((note) => <li key={note}>{note}</li>)}</ul> : null}
          </>
        ) : (
          <p>First flight in this view, so there is no earlier outline to compare. Step forward to see what each night changed.</p>
        )}
      </div>
    </div>
  );
}

function Contours({ data }: { data: ScrubData }) {
  return (
    <>
      <path className="ft-contour" d={data.minor} />
      <path className="ft-contour ft-contour--index" d={data.index} />
    </>
  );
}

function FlightScrub({ data, failed }: { data: ScrubData | null; failed: boolean }) {
  const [index, setIndex] = useState(cs.scrub.startIndex);
  const figureRef = useRef<HTMLElement>(null);
  const frames = data?.frames ?? [];
  const last = frames.length - 1;
  const go = useCallback((next: number) => setIndex(Math.max(0, Math.min(last, next))), [last]);

  // First-screen rule: on wide panes the map and its controls end inside the first screen.
  useLayoutEffect(() => {
    const figure = figureRef.current;
    if (!figure) return;
    const pane = figure.closest<HTMLElement>(".document-pane");
    const fit = () => {
      figure.style.removeProperty("--ft-map-h");
      if (!window.matchMedia("(min-width: 900px)").matches) return;
      const paneTop = pane ? pane.getBoundingClientRect().top - pane.scrollTop : -window.scrollY;
      const top = figure.getBoundingClientRect().top - paneTop;
      const available = (pane?.clientHeight ?? window.innerHeight) - top - 24;
      figure.style.setProperty("--ft-map-h", `${Math.max(340, Math.min(640, available))}px`);
    };
    fit();
    window.addEventListener("resize", fit);
    void document.fonts?.ready.then(fit);
    return () => window.removeEventListener("resize", fit);
  }, []);

  const frame = frames[index];
  const previous = frames[index - 1];
  const [x, y, , h] = SCRUB_VIEW;
  const barX = x + 30;
  const barY = y + h - 40;
  const title = frame
    ? `Dome Fire infrared outline flown ${day(pdt(frame.observed_at))}${previous ? `, with the ${day(pdt(previous.observed_at))} outline dashed and the change filled` : ""}`
    : cs.scrub.alt;

  return (
    <figure className="ft-scrub" ref={figureRef} aria-labelledby="ft-scrub-cap" data-analytics-section data-section-id="flight_scrub" data-section-type="demo">
      <div className="ft-map">
        {data ? (
          <svg viewBox={SCRUB_VIEW.join(" ")} preserveAspectRatio="xMidYMid slice" role="img" aria-label={title}>
            <Contours data={data} />
            <path className="ft-prev" d={previous?.d ?? ""} />
            <path className="ft-cur" d={frame.d} />
            <path className="ft-add" d={frame.add} />
            <path className="ft-rem" d={frame.rem} />
            <line className="ft-bar" x1={barX} y1={barY} x2={barX + 100} y2={barY} />
            <line className="ft-bar" x1={barX} y1={barY - 8} x2={barX} y2={barY + 1} />
            <line className="ft-bar" x1={barX + 100} y1={barY - 8} x2={barX + 100} y2={barY + 1} />
            <text className="ft-bar-t" x={barX + 112} y={barY + 8}>1 km</text>
            <text className="ft-map-label" x={x + 30} y={y + 52}>Dome Fire</text>
          </svg>
        ) : (
          <p className="ft-map-status" role="status">{failed ? "The map didn’t load. The recorded screenshot below shows the same step." : "Loading the Dome Fire flights…"}</p>
        )}
      </div>

      <div className="ft-read">
        {data ? <Readout frames={frames} index={index} /> : <div />}
        <div />
        <div className="ft-ctl">
          <div className="ft-key" aria-hidden="true">
            <span><i className="ft-key--cur" />This flight</span>
            <span><i className="ft-key--prev" />Previous flight</span>
            <span><i className="ft-key--add" />Added</span>
            <span><i className="ft-key--rem" />Removed</span>
          </div>
          <div className="ft-ctl-row">
            <button type="button" onClick={() => go(index - 1)} disabled={!data || index === 0} aria-label="Previous flight">
              <svg viewBox="0 0 14 14" aria-hidden="true"><path d="M10 1.5 3.5 7 10 12.5z" /></svg>
            </button>
            <input
              type="range"
              min={0}
              max={Math.max(last, 0)}
              step={1}
              value={index}
              disabled={!data}
              onChange={(event) => go(Number(event.target.value))}
              aria-label="Flight"
              aria-describedby="ft-scrub-cap"
              aria-valuetext={frame ? `${day(pdt(frame.observed_at))}, flight ${index + 1} of ${frames.length}` : undefined}
            />
            <button type="button" onClick={() => go(index + 1)} disabled={!data || index === last} aria-label="Next flight">
              <svg viewBox="0 0 14 14" aria-hidden="true"><path d="M4 1.5 10.5 7 4 12.5z" /></svg>
            </button>
          </div>
          <div className="ft-ticks" style={{ "--ft-ticks": Math.max(frames.length, 1) } as CSSProperties}>
            {frames.map((f, i) => {
              const d = pdt(f.observed_at);
              const month = i === 0 || d.getUTCDate() === 1 ? MONTHS[d.getUTCMonth()] : null;
              return (
                <button
                  key={f.id}
                  type="button"
                  onClick={() => go(i)}
                  aria-current={i === index ? "step" : undefined}
                  aria-label={`Flight of ${day(d)}`}
                >
                  <span>{d.getUTCDate()}</span>
                  {month ? <small>{month}</small> : null}
                </button>
              );
            })}
          </div>
        </div>
      </div>
      <figcaption id="ft-scrub-cap">{cs.scrub.caption}</figcaption>
    </figure>
  );
}

function ClockLanes() {
  const c = cs.clocks;
  const t0 = Date.parse(c.start);
  const span = Date.parse(c.end) - t0;
  const pct = (iso: string) => `${(((Date.parse(iso) - t0) / span) * 100).toFixed(2)}%`;
  const width = (ms: number) => `${((ms / span) * 100).toFixed(2)}%`;

  const lane = (l: FireTraceLane) => (
    <div className={`ft-lane ft-lane--${l.key}`} key={l.key}>
      <div className="ft-who"><b>{l.name}</b><span>{l.source}</span></div>
      <div className="ft-track">
        {l.band ? <div className="ft-band" style={{ left: pct(new Date(Date.parse(l.band.at) - l.band.seconds * 1000).toISOString()), width: width(2 * l.band.seconds * 1000) }} /> : null}
        {l.link ? <div className="ft-link" style={{ left: pct(l.link.from), width: width(Date.parse(l.link.to) - Date.parse(l.link.from)) }} /> : null}
        {l.events.map((e) => (
          <div key={e.at} className={`ft-ev ft-ev--${e.shape ?? "dot"}${e.above ? " is-above" : ""}`} style={{ left: pct(e.at) }}>
            <i /><b>{e.label}</b><span>{e.note}</span>
          </div>
        ))}
        <div className="ft-retr" style={{ left: pct(l.retrieved) }} />
        {l.key === "ir" ? <span className="ft-retr-t" style={{ right: `calc(100% - ${pct(l.retrieved)} + 8px)` }}>retrieved Oct 12</span> : null}
      </div>
      <div className="ft-acres">{l.acres}<small>acres</small></div>
    </div>
  );

  return (
    <>
      <div className="ft-clocks" role="img" aria-label={c.summary}>
        <div className="ft-axis" aria-hidden="true">
          <span />
          <div className="ft-track">
            {c.ticks.map(([at, label]) => <span key={at} style={{ left: pct(at) }}>{label}</span>)}
          </div>
          <span className="ft-acres-head">Mapped area</span>
        </div>
        <div aria-hidden="true">{c.lanes.map(lane)}</div>
        <p className="ft-clock-note" aria-hidden="true">{c.footnote}</p>
      </div>
      <div className="ft-clocklist">
        {c.lanes.map((l) => (
          <div key={l.key}>
            <h3>{l.name}, {l.acres} acres</h3>
            <dl>{l.list.map((row) => <Fragment key={row.term}><dt>{row.term}</dt><dd>{row.detail}</dd></Fragment>)}</dl>
          </div>
        ))}
      </div>
    </>
  );
}

function Disagreement({ data }: { data: ScrubData | null }) {
  const d = cs.disagreement;
  const lastFrame = data?.frames[data.frames.length - 1];
  return (
    <div className="ft-grid ft-dis">
      <figure className="ft-dis-map">
        <div className="ft-dis-frame">
          {data && lastFrame ? (
            <svg viewBox={DISAGREEMENT_VIEW} preserveAspectRatio="xMidYMid slice" role="img" aria-label={d.alt}>
              <Contours data={data} />
              <path className="ft-feds" d={data.feds} />
              <path className="ft-cur ft-cur--still" d={lastFrame.d} />
              <circle className="ft-lobe" cx={data.lobe[0]} cy={data.lobe[1]} r={115} />
              <text className="ft-lobe-t" x={data.lobe[0] - 70} y={data.lobe[1] + 165}>{d.lobeLabel}</text>
            </svg>
          ) : null}
        </div>
        <figcaption>{d.caption}</figcaption>
      </figure>
      <div className="ft-dis-side">
        <h3>{d.title}</h3>
        <p>{d.body}</p>
        <div className="ft-stack">
          <div>
            <div className="ft-stack-lab"><span>{d.bars.ir.label}</span><b>{d.bars.ir.value}</b></div>
            <div className="ft-stack-bar"><i className="ft-tone--ir" style={{ width: `${d.irShare}%` }} /></div>
          </div>
          <div>
            <div className="ft-stack-lab"><span>{d.bars.feds.label}</span><b>{d.bars.feds.value}</b></div>
            <div className="ft-stack-bar">{d.parts.map((p) => <i key={p.tone} className={`ft-tone--${p.tone}`} style={{ width: `${p.share}%` }} />)}</div>
          </div>
        </div>
        <ul className="ft-parts">
          {d.parts.map((p) => <li key={p.tone}><i className={`ft-tone--${p.tone}`} /><span>{p.label}</span><span>{p.value}</span></li>)}
        </ul>
        <p className="ft-note">{d.note}</p>
      </div>
    </div>
  );
}

